"""
Debate schemas and data models for AI Debate Studio in TradeLab.

Covers:
- MarketSnapshot: point-in-time technical and derivative indicator matrix.
- BullAgentOutput: bullish conviction, strike, thesis, and supporting arguments.
- BearAgentOutput: bearish conviction, strike, thesis, and supporting arguments.
- JudgeAgentOutput: CRO institutional decision, strike, SL, target, R:R, and rationale.
- DebateSession: full multi-agent debate session with execution status.
"""

from __future__ import annotations

from datetime import datetime
from typing import Any, Literal, Optional
from zoneinfo import ZoneInfo
from pydantic import BaseModel, Field, computed_field

IST = ZoneInfo("Asia/Kolkata")


def ist_now_str() -> str:
    """Return formatted ISO timestamp in Indian Standard Time (IST)."""
    return datetime.now(IST).strftime("%Y-%m-%d %H:%M:%S IST")


class MarketSnapshot(BaseModel):
    """Point-in-time market data ingested by the debate agents."""

    symbol: str = Field(default="NIFTY", description="Underlying index: NIFTY or BANKNIFTY")
    spot_price: float = Field(..., description="Current index spot price")
    ema_20: float = Field(..., description="20-period Exponential Moving Average")
    ema_50: float = Field(..., description="50-period Exponential Moving Average")
    vwap: float = Field(..., description="Volume Weighted Average Price")
    rsi: float = Field(..., description="14-period Relative Strength Index")
    volume: float = Field(default=1000000.0, description="Session volume")
    atr: float = Field(default=120.0, description="14-period Average True Range")
    vix: float = Field(default=14.5, description="India VIX")
    pcr: float = Field(default=1.0, description="Put-Call Ratio (OI)")
    ce_oi_change: float = Field(default=0.0, description="Net CE Open Interest change")
    pe_oi_change: float = Field(default=0.0, description="Net PE Open Interest change")
    higher_tf_trend: str = Field(default="NEUTRAL", description="BULLISH / BEARISH / NEUTRAL")
    timestamp: str = Field(default_factory=ist_now_str)
    atm_strike: float = Field(default=24500.0, description="ATM strike price")
    day_high: Optional[float] = None
    day_low: Optional[float] = None
    day_open: Optional[float] = None
    max_pain: Optional[float] = None
    call_oi_wall: Optional[float] = None
    put_oi_wall: Optional[float] = None
    cpr_pivot: Optional[float] = None
    cpr_bc: Optional[float] = None
    cpr_tc: Optional[float] = None
    cpr_width_type: str = "NARROW_TRENDING"
    supertrend_direction: str = "BULLISH"
    supertrend_value: Optional[float] = None
    advance_decline_ratio: Optional[float] = 1.2
    heavyweights_alignment: Optional[str] = "BULLISH"
    fii_sentiment: Optional[str] = "NEUTRAL"
    global_sentiment: Optional[str] = "POSITIVE"


class BullAgentOutput(BaseModel):
    """Output generated by the Bull (bullish options) agent."""

    bias: Literal["BULLISH"] = "BULLISH"
    confidence: int = Field(..., ge=1, le=10, description="Conviction score (1-10)")
    strike: float = Field(..., description="Recommended strike price")
    thesis: str = Field(..., description="Core bullish thesis statement")
    arguments: list[str] = Field(..., min_length=1, description="List of structured bullish arguments")
    recommended_strike: Optional[str] = Field(default=None, description="Formatted strike e.g. '24500CE'")
    key_levels: dict[str, Any] = Field(default_factory=dict, description="Support, resistance, breakout targets")

    @computed_field
    @property
    def confidence_score(self) -> int:
        return self.confidence

    @computed_field
    @property
    def key_arguments(self) -> list[str]:
        return self.arguments


class BearAgentOutput(BaseModel):
    """Output generated by the Bear (bearish options) agent."""

    bias: Literal["BEARISH"] = "BEARISH"
    confidence: int = Field(..., ge=1, le=10, description="Conviction score (1-10)")
    strike: float = Field(..., description="Recommended strike price")
    thesis: str = Field(..., description="Core bearish thesis statement")
    arguments: list[str] = Field(..., min_length=1, description="List of structured bearish arguments")
    recommended_strike: Optional[str] = Field(default=None, description="Formatted strike e.g. '24500PE'")
    key_levels: dict[str, Any] = Field(default_factory=dict, description="Resistance, breakdown targets")

    @computed_field
    @property
    def confidence_score(self) -> int:
        return self.confidence

    @computed_field
    @property
    def key_arguments(self) -> list[str]:
        return self.arguments


class JudgeAgentOutput(BaseModel):
    """Final decision rendered by the institutional Judge / Chief Risk Officer agent."""

    verdict: Literal["BUY CE", "BUY PE", "NO_TRADE"] = Field(..., description="Trading action")
    confidence: int = Field(..., ge=1, le=10, description="Judge conviction (1-10)")
    recommended_strike: float = Field(default=0.0, description="Strike price recommended")
    selected_strike: Optional[str] = Field(default=None, description="Strike string e.g. '24500CE'")
    entry_price: float = Field(default=0.0, description="Estimated option premium entry price")
    stop_loss: float = Field(default=0.0, description="Stop-loss price in option premium")
    target: float = Field(default=0.0, description="Target price in option premium")
    risk_reward_ratio: Any = Field(default="N/A", description="Risk-reward ratio (e.g. 1.5 or '1:1.5')")
    reasoning: str = Field(..., description="Winning thesis summary and CRO rationale")
    key_risks: list[str] = Field(default_factory=list, description="Primary market risks")
    risk_warning: Optional[str] = Field(default=None, description="Risk warning text")

    # Compatibility aliases
    @computed_field
    @property
    def decision(self) -> str:
        if "CE" in self.verdict:
            return "BUY_CE"
        if "PE" in self.verdict:
            return "BUY_PE"
        return "NO_TRADE"

    @computed_field
    @property
    def entry_price_estimate(self) -> float:
        return self.entry_price

    @computed_field
    @property
    def winning_argument_summary(self) -> str:
        return self.reasoning

    @computed_field
    @property
    def sl(self) -> float:
        return self.stop_loss

    @computed_field
    @property
    def target_price(self) -> float:
        return self.target


class DebateSession(BaseModel):
    """Full persistent session record of a 3-agent AI debate."""

    id: str = Field(..., description="Unique debate identifier")
    timestamp: str = Field(default_factory=ist_now_str)
    symbol: str = Field(default="NIFTY", description="Underlying index")
    spot_price: float = Field(..., description="Spot index price at debate time")
    market_snapshot: MarketSnapshot
    bull: BullAgentOutput
    bear: BearAgentOutput
    judge: JudgeAgentOutput
    executed: bool = Field(default=False, description="Whether the judge's trade was executed")
    order_id: Optional[str] = Field(default=None, description="Associated paper trade order ID if executed")
    position_id: Optional[str] = Field(default=None, description="Paper position ID created by the execution")
    user_id: Optional[int] = Field(default=None, description="Account the trade was executed in")
    auto_executed: bool = Field(default=False, description="True when the scheduler executed it")
    skip_reason: Optional[str] = Field(default=None, description="Why a BUY verdict was not executed")
    exec_entry_price: Optional[float] = Field(default=None, description="Live option price actually filled")
    exec_symbol: Optional[str] = Field(default=None, description="Exchange trading symbol of the traded option")

    @computed_field
    @property
    def index_symbol(self) -> str:
        return self.symbol

    @computed_field
    @property
    def verdict(self) -> str:
        return self.judge.verdict

    @computed_field
    @property
    def bull_output(self) -> BullAgentOutput:
        return self.bull

    @computed_field
    @property
    def bear_output(self) -> BearAgentOutput:
        return self.bear

    @computed_field
    @property
    def judge_decision(self) -> JudgeAgentOutput:
        return self.judge
